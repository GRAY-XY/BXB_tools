import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as z from "zod/v4";
import { createToolDefinitions } from "../../backend/src/tool-definitions.js";
import { extraToolDefinitions } from "../../skills/banxuebang/scripts/extra-tools.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const skillRoot = path.join(repoRoot, "skills", "banxuebang");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some(arg => arg !== "--check")) throw new Error("Usage: node release/scripts/sync-agent-skill.mjs [--check]");
const runtimeFiles = ["academic-context-coordinator.js", "banxuebang-client.js", "code-image-preview.js",
  "draft-attachments.js", "draft-store.js", "model-image.js", "playwright-runtime.js", "session-store.js", "tool-definitions.js"];
const generated = new Map();
const hashes = {};
const normalized = buffer => Buffer.from(buffer.toString("utf8").replace(/\r\n?/g, "\n"));
for (const file of runtimeFiles) {
  const buffer = normalized(await readFile(path.join(repoRoot, "backend", "src", file)));
  generated.set(`runtime/${file}`, buffer);
  hashes[`backend/src/${file}`] = createHash("sha256").update(buffer).digest("hex");
}
const rootPackage = JSON.parse(await readFile(path.join(repoRoot, "package.json"), "utf8"));
const packageInfo = {
  name: "@gray-xy/banxuebang-agent-skill", version: "1.0.0", private: true, type: "module", license: "MIT",
  description: "Standalone Banxuebang Agent Skill with every shared tool, code previews, CLI, and MCP stdio.",
  scripts: { setup: "node scripts/setup.mjs", doctor: "node scripts/bxb.mjs doctor",
    tools: "node scripts/bxb.mjs list", mcp: "node scripts/mcp.mjs" },
  engines: { node: ">=22.19.0" }, dependencies: rootPackage.dependencies,
};
const lock = JSON.parse(await readFile(path.join(repoRoot, "package-lock.json"), "utf8"));
lock.name = packageInfo.name;
lock.version = packageInfo.version;
lock.packages[""] = { name: packageInfo.name, version: packageInfo.version, license: packageInfo.license,
  dependencies: packageInfo.dependencies, engines: packageInfo.engines };
const json = value => `${JSON.stringify(value, null, 2)}\n`;
generated.set("package.json", json(packageInfo));
generated.set("package-lock.json", json(lock));
generated.set(".nvmrc", normalized(await readFile(path.join(repoRoot, ".nvmrc"))));
generated.set("LICENSE", normalized(await readFile(path.join(repoRoot, "LICENSE"))));

const remoteWrites = new Set(["send_private_message_text", "send_approved_draft_private_message",
  "upload_submission_file", "submit_task_result", "submit_approved_draft"]);
const contextWrites = new Set(["set_current_term", "set_current_subject", "refresh_context"]);
const login = new Set(["interactive_login", "login_in_browser", "login_with_credentials", "import_browser_storage"]);
const localDeletes = new Set(["clear_session", "delete_submission_draft", "delete_workspace_file"]);
const localWrites = new Set(["download_task_attachment", "read_task_attachment", "collect_task_submission_context",
  "rename_workspace_file", "write_workspace_text_file", "draft_task_submission", "update_submission_draft",
  "approve_submission_draft", "reject_submission_draft", "render_code_as_vscode_image", "render_pdf_pages",
  "import_workspace_files", "browser_capture_achievement_page"]);
function effect(name) {
  if (remoteWrites.has(name)) return "remote-write";
  if (contextWrites.has(name)) return "account-context";
  if (login.has(name)) return "login/session-write";
  if (localDeletes.has(name)) return "local-delete";
  if (localWrites.has(name)) return "local-write";
  if (name === "run_python_snippet") return "local-code-execution";
  return "read/preview";
}
const baseTools = createToolDefinitions({});
const extraTools = extraToolDefinitions({}, z);
const allTools = [...baseTools, ...extraTools];
if (new Set(allTools.map(tool => tool.name)).size !== allTools.length) throw new Error("Duplicate tool names.");
const tools = allTools.map(tool => ({ name: tool.name, description: tool.description, effect: effect(tool.name),
  origin: baseTools.includes(tool) ? "shared-backend" : "standalone-adapter",
  inputSchema: z.toJSONSchema(z.object(tool.inputSchema || {})) }));
generated.set("references/tools.json", json({ schemaVersion: 1, toolCount: tools.length,
  sharedToolCount: baseTools.length, tools }));
const rows = tools.map(tool => {
  const required = tool.inputSchema.required || [];
  return `| \`${tool.name}\` | ${tool.effect} | ${required.map(key => `\`${key}\``).join(", ") || "none"} | ${tool.description.replaceAll("|", "\\|").replaceAll("\n", " ")} |`;
});
generated.set("references/tools.md", `# Complete Tool Catalog\n\nGenerated by \`release/scripts/sync-agent-skill.mjs\`; do not edit this catalog or the vendored \`runtime/\` manually.\n\n${tools.length} callable tools: all ${baseTools.length} shared backend tools plus ${extraTools.length} standalone adapters. Exact JSON Schemas are in [tools.json](tools.json). Inspect one schema with \`node scripts/bxb.mjs describe TOOL\`.\n\nThe package exposes every listed tool. Effect labels guide the calling agent; they are not a permission sandbox. Remote writes require authorization for the concrete destination and content. Draft delivery uses the reviewed preview's confirmation token and exact attachment selection. Local Python execution has a timeout, not a security sandbox.\n\n| Tool | Effect | Required arguments | Purpose |\n| --- | --- | --- | --- |\n${rows.join("\n")}\n`);
generated.set("runtime-manifest.json", json({ schemaVersion: 1, sourceRepository: "https://github.com/GRAY-XY/BXB_tools",
  runtimeFiles: hashes, sourceLineEndings: "LF",
  dependencyLockSha256: createHash("sha256").update(normalized(await readFile(path.join(repoRoot, "package-lock.json")))).digest("hex"),
  toolCount: tools.length, sharedToolCount: baseTools.length }));
let differences = 0;
for (const [relative, value] of generated) {
  const target = path.join(skillRoot, relative);
  const buffer = Buffer.isBuffer(value) ? value : Buffer.from(value);
  if (check) {
    const actual = await readFile(target).catch(() => null);
    if (!actual || !actual.equals(buffer)) { console.error(`Out of sync: skills/banxuebang/${relative}`); differences++; }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, buffer);
  }
}
if (differences) process.exitCode = 1;
else console.log(`${check ? "Verified" : "Generated"} standalone skill: ${tools.length} tools, ${runtimeFiles.length} runtime source files.`);
